"""Extract and audit the supplied archive without changing source CSV values."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def extract(archive: Path, target: Path) -> list[Path]:
    target.mkdir(parents=True, exist_ok=True)
    paths = []
    with zipfile.ZipFile(archive) as source:
        for member in source.infolist():
            relative = Path(member.filename)
            destination = (target / relative).resolve()
            if not destination.is_relative_to(target.resolve()):
                raise ValueError(f'Unsafe archive path: {member.filename}')
            if member.is_dir():
                continue
            if destination.suffix.lower() != '.csv':
                raise ValueError(f'Unexpected non-CSV member: {member.filename}')
            destination.parent.mkdir(parents=True, exist_ok=True)
            # Copy bytes verbatim. Re-runs restore exactly the supplied inputs.
            with source.open(member) as src, destination.open('wb') as dst:
                while block := src.read(1024 * 1024):
                    dst.write(block)
            paths.append(destination)
    return sorted(paths)


def audit_csv(path: Path) -> dict:
    with path.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        columns = reader.fieldnames
        if not columns or len(set(columns)) != len(columns):
            raise ValueError(f'Invalid header: {path}')
        stats = {name: {'missing': 0, 'values': set(), 'examples': []} for name in columns}
        seen_rows = set()
        duplicates = 0
        count = 0
        for row in reader:
            if None in row or any(value is None for value in row.values()):
                raise ValueError(f'Malformed CSV record {count + 2}: {path}')
            count += 1
            fingerprint = hashlib.sha256(json.dumps(list(row.values()), ensure_ascii=False).encode()).digest()
            duplicates += fingerprint in seen_rows
            seen_rows.add(fingerprint)
            for name, value in row.items():
                stat = stats[name]
                if not value.strip():
                    stat['missing'] += 1
                else:
                    stat['values'].add(value)
                    if len(stat['examples']) < 3 and value not in stat['examples']:
                        stat['examples'].append(value[:160])
    summary = {}
    for name, stat in stats.items():
        summary[name] = {
            'missing_count': stat['missing'],
            'missing_pct': round(100 * stat['missing'] / count, 6) if count else 0,
            'distinct_nonempty': len(stat['values']),
            'examples': stat['examples'],
        }
    return {
        'filename': path.name, 'sha256': sha256(path), 'rows': count,
        'column_count': len(columns), 'exact_duplicate_rows': duplicates,
        'candidate_single_column_keys': [name for name, s in summary.items()
                                       if s['missing_count'] == 0 and s['distinct_nonempty'] == count],
        'columns': summary,
    }


def write_markdown(report: dict, target: Path) -> None:
    lines = ['# Supplied dataset audit', '',
             'Generated by `python scripts/inspect_dataset.py`. Missing means empty or whitespace-only.',
             'Candidate keys below are observed uniqueness, not assumed business identifiers.', '',
             f"Archive SHA-256: `{report['archive_sha256']}`", '',
             '| File | Rows | Columns | Exact duplicate rows | Candidate single-column keys |',
             '|---|---:|---:|---:|---|']
    for table in report['files']:
        lines.append(f"| {table['filename']} | {table['rows']:,} | {table['column_count']} | "
                     f"{table['exact_duplicate_rows']:,} | {', '.join(table['candidate_single_column_keys']) or 'None'} |")
    for table in report['files']:
        lines += ['', f"## {table['filename']}", '',
                  '| Column | Missing count | Missing % | Distinct nonempty |', '|---|---:|---:|---:|']
        for name, stat in table['columns'].items():
            lines.append(f"| {name} | {stat['missing_count']:,} | {stat['missing_pct']:.4f}% | {stat['distinct_nonempty']:,} |")
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--raw-dir', type=Path, default=ROOT / 'data/raw')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'docs/generated')
    args = parser.parse_args()
    archives = sorted(ROOT.glob('*.zip')) if args.archive is None else [args.archive]
    if len(archives) != 1:
        parser.error('Provide --archive when there is not exactly one ZIP in the repository root.')
    archive = archives[0]
    paths = extract(archive, args.raw_dir)
    tables = []
    for path in paths:
        result = audit_csv(path)
        tables.append(result)
        print(f"{path.name}: {result['rows']:,} rows, {result['column_count']} columns", flush=True)
    report = {'archive': archive.name, 'archive_sha256': sha256(archive), 'files': tables}
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / 'dataset_audit.json').write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    write_markdown(report, args.output_dir / 'dataset_audit.md')


if __name__ == '__main__':
    main()
